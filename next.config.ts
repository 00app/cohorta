import type { NextConfig } from "next";

// Content-Security-Policy is set dynamically in src/proxy.ts (needs a
// fresh nonce per request so Next's own hydration script can satisfy
// script-src without 'unsafe-inline') — not listed here to avoid two
// conflicting CSP headers on the same response. Everything else here is
// static and applies to every route regardless.
const securityHeaders = [
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), browsing-topics=()",
  },
];

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
